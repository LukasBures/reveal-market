#!/usr/bin/env bash
# scripts/generate_env.sh
# ---------------------------------------------------------------
# Assembles a .env file from environment variables.
# Designed for CI/CD pipelines (GitHub Actions) where secrets and
# variables are injected as env vars before this script runs.
#
# Usage:
#   ./scripts/generate_env.sh                        # writes .env.production
#   ./scripts/generate_env.sh .env.staging           # custom output path
#   ./scripts/generate_env.sh --validate-only        # check required vars, don't write
# ---------------------------------------------------------------
set -euo pipefail

OUTPUT="${1:-.env.production}"
VALIDATE_ONLY=false
if [[ "${1:-}" == "--validate-only" ]]; then
    VALIDATE_ONLY=true
fi

# ---- Required secrets (must be set in CI environment) ----
REQUIRED_SECRETS=<REDACTED>
    REDIS_PASSWORD
    RM_DATABASE_URL
    RM_DATABASE_ASYNC_URL
    RM_PRICING_SIGNER_PRIVATE_KEY
    RM_AUTHORIZATION_SIGNER_PRIVATE_KEY
    RM_WALLET_PRIVATE_KEY
    RM_SETTLEMENT_SIGNER_PRIVATE_KEY
    RM_RELAYER_PRIVATE_KEY
    RM_RELAYER_BEARER_TOKEN
    RM_RELAYER_API_INTERNAL_SECRET
    RM_INTERNAL_API_SECRET
    RM_PROVER_SHARED_SECRET
    RM_HEDGER_INTERNAL_SECRET
    HEDGER_ADMIN_INTERNAL_SECRET
    CF_API_TOKEN
    GRAFANA_ADMIN_PASSWORD
    DEPLOYER_KEY
    RM_RELAYER_WEBHOOK_SECRET
)

# ---- Required variables (non-secret, deployment-specific) ----
REQUIRED_VARS=(
    RM_RPC_URL
    RM_CHAIN_ID
    RM_FACTORY_ADDRESS
    RM_PROTOCOL_POOL_ADDRESS
    RM_RELAYER_ESCROW_ADDRESS
    RM_MARKET_IMPLEMENTATION_ADDRESS
    RM_VERIFIER_ADDRESS
    RM_AUTHORIZATION_SIGNER
    RM_ORACLE_ADDRESS
    ZEN_TOKEN_ADDRESS
    PROVER_CIRCUIT_HASH
    NEXT_PUBLIC_WALLETCONNECT_PROJECT_ID
    NEXT_PUBLIC_CHAIN_ID
)

# ---- Validate ----
missing=()
for var in "${REQUIRED_SECRETS[@]}" "${REQUIRED_VARS[@]}"; do
    if [[ -z "${!var:-}" ]]; then
        missing+=("$var")
    fi
done

if (( ${#missing[@]} > 0 )); then
    echo "ERROR: Missing required environment variables:" >&2
    printf '  - %s\n' "${missing[@]}" >&2
    exit 1
fi

if $VALIDATE_ONLY; then
    echo "All required variables present."
    exit 0
fi

# ---- Derived defaults ----
RM_CHAIN_ID="${RM_CHAIN_ID:-2651420}"
RM_WALLET_ADDRESS="${RM_WALLET_ADDRESS:-}"
PRICING_SIGNER_ADDRESS="${PRICING_SIGNER_ADDRESS:-${RM_AUTHORIZATION_SIGNER}}"
RELAYER_ESCROW_ADDRESS="${RM_RELAYER_ESCROW_ADDRESS}"
NEXT_PUBLIC_RPC_URL="${NEXT_PUBLIC_RPC_URL:-${RM_RPC_URL}}"
NEXT_PUBLIC_BLOCK_EXPLORER_URL="${NEXT_PUBLIC_BLOCK_EXPLORER_URL:-https://horizen-testnet.explorer.caldera.xyz}"
NEXT_PUBLIC_ZEN_TOKEN_ADDRESS="${NEXT_PUBLIC_ZEN_TOKEN_ADDRESS:-${ZEN_TOKEN_ADDRESS}}"
NEXT_PUBLIC_RELAYER_ESCROW_ADDRESS="${NEXT_PUBLIC_RELAYER_ESCROW_ADDRESS:-${RM_RELAYER_ESCROW_ADDRESS}}"
NEXT_PUBLIC_GA_MEASUREMENT_ID="${NEXT_PUBLIC_GA_MEASUREMENT_ID:-}"
CONTACT_TURNSTILE_SITE_KEY="${CONTACT_TURNSTILE_SITE_KEY:-}"
CONTACT_TURNSTILE_SECRET=<REDACTED>
CONTACT_DISCORD_WEBHOOK_URL=<REDACTED>
HEDGER_VAULT_PRIVATE_KEY=<REDACTED>
RM_HEDGER_INTERNAL_SECRET=<REDACTED>
HEDGER_ADMIN_INTERNAL_SECRET=<REDACTED>
PROVER_ARTIFACTS_SSH_KEY_PATH="${PROVER_ARTIFACTS_SSH_KEY_PATH:-}"
GRAFANA_ADMIN_USER="${GRAFANA_ADMIN_USER:-admin}"
RM_RELAYER_BASE_URL="${RM_RELAYER_BASE_URL:-http://relayer:8088}"
RM_PROVER_BASE_URL="${RM_PROVER_BASE_URL:-http://prover:8085}"
RM_POLYMARKET_API_BASE="${RM_POLYMARKET_API_BASE:-https://gamma-api.polymarket.com}"
HEDGER_ALLOWED_HOSTS="${HEDGER_ALLOWED_HOSTS:-[\"hedger\",\"hedger:8090\",\"localhost\",\"127.0.0.1\"]}"
HEDGER_CORS_ALLOW_ORIGINS="${HEDGER_CORS_ALLOW_ORIGINS:-[\"http://api:8000\",\"http://hedger:8090\"]}"
DISCORD_ALERT_WEBHOOK_URL=<REDACTED>
NEXT_PUBLIC_SITE_URL="${NEXT_PUBLIC_SITE_URL:-https://revealmarket.xyz}"
NEXT_PUBLIC_API_BASE_URL="${NEXT_PUBLIC_API_BASE_URL:-https://api.revealmarket.xyz}"
NEXT_PUBLIC_PRICE_STREAMER_URL="${NEXT_PUBLIC_PRICE_STREAMER_URL:-https://stream.revealmarket.xyz}"

# ---- Write ----
echo "Generating ${OUTPUT} ..."

cat > "${OUTPUT}" <<EOF
# Generated by scripts/generate_env.sh — do not edit manually.
# All tuning knobs default in code via env_presets.py.
# This file contains only secrets + deployment-specific config.

# --- Core ---
RM_ENVIRONMENT=production

# --- Infrastructure ---
REDIS_PASSWORD=${REDIS_PASSWORD}
RM_DATABASE_URL=${RM_DATABASE_URL}
RM_DATABASE_ASYNC_URL=${RM_DATABASE_ASYNC_URL}
RM_REDIS_URL=redis://:${REDIS_PASSWORD}@redis:6379/0
STREAMER_REDIS_URL=redis://:${REDIS_PASSWORD}@redis:6379/0
HEDGER_REDIS_URL=redis://:${REDIS_PASSWORD}@redis:6379/0

# --- Signing keys ---
RM_PRICING_SIGNER_PRIVATE_KEY=${RM_PRICING_SIGNER_PRIVATE_KEY}
RM_AUTHORIZATION_SIGNER_PRIVATE_KEY=${RM_AUTHORIZATION_SIGNER_PRIVATE_KEY}
RM_WALLET_PRIVATE_KEY=${RM_WALLET_PRIVATE_KEY}
RM_SETTLEMENT_SIGNER_PRIVATE_KEY=${RM_SETTLEMENT_SIGNER_PRIVATE_KEY}
RM_RELAYER_PRIVATE_KEY=${RM_RELAYER_PRIVATE_KEY}
HEDGER_VAULT_PRIVATE_KEY=${HEDGER_VAULT_PRIVATE_KEY}
DEPLOYER_KEY=${DEPLOYER_KEY}

# --- Internal auth tokens ---
RM_RELAYER_BEARER_TOKEN=${RM_RELAYER_BEARER_TOKEN}
RM_RELAYER_API_INTERNAL_SECRET=${RM_RELAYER_API_INTERNAL_SECRET}
RM_INTERNAL_API_SECRET=${RM_INTERNAL_API_SECRET}
RM_PROVER_SHARED_SECRET=${RM_PROVER_SHARED_SECRET}
RM_HEDGER_INTERNAL_SECRET=${RM_HEDGER_INTERNAL_SECRET}
HEDGER_ADMIN_INTERNAL_SECRET=${HEDGER_ADMIN_INTERNAL_SECRET}
GRAFANA_ADMIN_USER=${GRAFANA_ADMIN_USER}
GRAFANA_ADMIN_PASSWORD=${GRAFANA_ADMIN_PASSWORD}
CF_API_TOKEN=${CF_API_TOKEN}

# --- Service URLs (docker-internal defaults) ---
RM_RELAYER_BASE_URL=${RM_RELAYER_BASE_URL}
RM_PROVER_BASE_URL=${RM_PROVER_BASE_URL}
RM_POLYMARKET_API_BASE=${RM_POLYMARKET_API_BASE}

# --- Hedger ---
HEDGER_ALLOWED_HOSTS=${HEDGER_ALLOWED_HOSTS}
HEDGER_CORS_ALLOW_ORIGINS=${HEDGER_CORS_ALLOW_ORIGINS}

# --- Chain & contract addresses ---
RM_RPC_URL=${RM_RPC_URL}
RM_CHAIN_ID=${RM_CHAIN_ID}
RM_FACTORY_ADDRESS=${RM_FACTORY_ADDRESS}
RM_PROTOCOL_POOL_ADDRESS=${RM_PROTOCOL_POOL_ADDRESS}
RM_RELAYER_ESCROW_ADDRESS=${RM_RELAYER_ESCROW_ADDRESS}
RM_MARKET_IMPLEMENTATION_ADDRESS=${RM_MARKET_IMPLEMENTATION_ADDRESS}
RM_VERIFIER_ADDRESS=${RM_VERIFIER_ADDRESS}
RM_AUTHORIZATION_SIGNER=${RM_AUTHORIZATION_SIGNER}
RM_ORACLE_ADDRESS=${RM_ORACLE_ADDRESS}
ZEN_TOKEN_ADDRESS=${ZEN_TOKEN_ADDRESS}
RM_WALLET_ADDRESS=${RM_WALLET_ADDRESS}
RELAYER_ESCROW_ADDRESS=${RELAYER_ESCROW_ADDRESS}
PRICING_SIGNER_ADDRESS=${PRICING_SIGNER_ADDRESS}

# --- Frontend build-time vars ---
NEXT_PUBLIC_SITE_URL=${NEXT_PUBLIC_SITE_URL}
NEXT_PUBLIC_API_BASE_URL=${NEXT_PUBLIC_API_BASE_URL}
NEXT_PUBLIC_PRICE_STREAMER_URL=${NEXT_PUBLIC_PRICE_STREAMER_URL}
NEXT_PUBLIC_WALLETCONNECT_PROJECT_ID=${NEXT_PUBLIC_WALLETCONNECT_PROJECT_ID}
NEXT_PUBLIC_ZEN_TOKEN_ADDRESS=${NEXT_PUBLIC_ZEN_TOKEN_ADDRESS}
NEXT_PUBLIC_RELAYER_ESCROW_ADDRESS=${NEXT_PUBLIC_RELAYER_ESCROW_ADDRESS}
NEXT_PUBLIC_CHAIN_ID=${NEXT_PUBLIC_CHAIN_ID}
NEXT_PUBLIC_RPC_URL=${NEXT_PUBLIC_RPC_URL}
NEXT_PUBLIC_BLOCK_EXPLORER_URL=${NEXT_PUBLIC_BLOCK_EXPLORER_URL}
NEXT_PUBLIC_GA_MEASUREMENT_ID=${NEXT_PUBLIC_GA_MEASUREMENT_ID}

# --- Contact form ---
CONTACT_TURNSTILE_SITE_KEY=${CONTACT_TURNSTILE_SITE_KEY}
CONTACT_TURNSTILE_SECRET=${CONTACT_TURNSTILE_SECRET}
CONTACT_DISCORD_WEBHOOK_URL=${CONTACT_DISCORD_WEBHOOK_URL}

# --- Prover ---
PROVER_CIRCUIT_HASH=${PROVER_CIRCUIT_HASH}
PROVER_ARTIFACTS_SSH_KEY_PATH=${PROVER_ARTIFACTS_SSH_KEY_PATH}

# --- Hardening ---
RM_RELAYER_WEBHOOK_SECRET=${RM_RELAYER_WEBHOOK_SECRET}
DISCORD_ALERT_WEBHOOK_URL=${DISCORD_ALERT_WEBHOOK_URL}
EOF

echo "Wrote ${OUTPUT} ($(wc -l < "${OUTPUT}") lines)"
